#!/usr/bin/env python3
"""Hash an explicit, trusted allowlist of application build outputs.

Outputs must be nonempty regular files without symlinks in any path component.
The same manifest is generated by two independent application-build workers.
It records only the declared files; an independent builder must build from a fresh
checkout and not unstash the first worker's outputs.
"""
import argparse
import hashlib
import json
import pathlib
import re
import stat


def manifest(root, paths):
    base = pathlib.Path(root).resolve(strict=True)
    # Same separators the original Jenkins `stash includes:` (for compatibility) accepts: commas and/or whitespace. Paths with
    # spaces, quotes or glob characters are not supported and fail closed below.
    names = [n for n in re.split(r'[,\s]+', paths) if n]
    if any(c in n for n in names for c in '*?[]"\'\\'):
        raise ValueError('build output paths must be literal file names (no patterns or quoting)')
    if not names or len(names) > 100 or len(set(names)) != len(names):
        raise ValueError('expected a unique nonempty set of <=100 artifact paths')
    result = []
    for name in sorted(names):
        part = pathlib.PurePosixPath(name)
        if part.is_absolute() or not name or any(p in ('', '.', '..') for p in part.parts):
            raise ValueError(f'unsafe build output path: {name!r}')
        current = base
        for piece in part.parts:
            current = current / piece
            entry = current.lstat()
            if stat.S_ISLNK(entry.st_mode):
                raise ValueError(f'symlinks forbidden in build output path: {name!r}')
        if not stat.S_ISREG(current.stat().st_mode):
            raise ValueError(f'build output must be regular file: {name!r}')
        h = hashlib.sha256()
        with current.open('rb') as f:
            while chunk := f.read(1024 * 1024):
                h.update(chunk)
        result.append({'path': name, 'size': current.stat().st_size, 'sha256': h.hexdigest()})
    return {'schema': 'https://example.org/verified-build-artifacts/v1', 'files': result}


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--root', required=True)
    p.add_argument('--paths', required=True)
    p.add_argument('--output', required=True)
    a = p.parse_args()
    try:
        data = manifest(a.root, a.paths)
        pathlib.Path(a.output).write_text(json.dumps(data, indent=2, sort_keys=True) + '\n')
    except (ValueError, OSError) as exc:
        raise SystemExit(f'INVALID APPLICATION ARTIFACT: {exc}')


if __name__ == '__main__':
    main()
